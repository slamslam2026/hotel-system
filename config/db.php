<?php
// فتح وسم PHP لبدء كتابة كود PHP

/**
 * ملف الاتصال بقاعدة البيانات
 * نستخدم PDO للأمان
 */
// تعليق متعدد الأسطر (DocBlock):
// يبدأ بـ /** وينتهي بـ */
// يوضح اسم الملف والغرض منه
// PDO = PHP Data Objects (طريقة آمنة للتعامل مع قواعد البيانات)

$host     = 'localhost';
// اسم المضيف (Host): المكان الذي توجد فيه قاعدة البيانات
// localhost = السيرفر المحلي (جهازك نفسه)
// في الاستضافة الحقيقية قد يكون: localhost أو IP أو اسم نطاق

$dbname   = 'hotel_db';
// اسم قاعدة البيانات التي نريد الاتصال بها
// يجب أن تكون موجودة مسبقاً في MySQL

$username = 'root';
// اسم المستخدم للاتصال بـ MySQL
// root = المستخدم الافتراضي في XAMPP/WAMP (كامل الصلاحيات)

$password = '';
// كلمة المرور للمستخدم
// فارغة '' لأن root في السيرفر المحلي عادةً بلا كلمة مرور
// ⚠️ تحذير: في الاستضافة الحقيقية يجب وضع كلمة مرور قوية

try {
// بداية كتلة try: نضع فيها الكود الذي قد يُسبِّب خطأ
// إذا حدث خطأ → ينتقل التنفيذ إلى catch
// الفائدة: بدلاً من توقف السكربت فجأة، نتعامل مع الخطأ بأناقة

    $pdo = new PDO(
    // إنشاء كائن جديد من كلاس PDO
    // $pdo = المتغير الذي سنستخدمه في كل استعلامات قاعدة البيانات لاحقاً
    // new PDO(...) = استدعاء الباني (Constructor) مع 4 معاملات

        "mysql:host=$host;dbname=$dbname;charset=utf8mb4",
        // المعامل الأول: سلسلة الاتصال (DSN = Data Source Name)
        // تخبر PDO بمكان الاتصال:
        // - mysql: نوع قاعدة البيانات
        // - host=$host: المضيف (localhost)
        // - dbname=$dbname: اسم قاعدة البيانات (hotel_db)
        // - charset=utf8mb4: ترميز الأحرف (يدعم العربية + الإيموجي)
        // ملاحظة: utf8mb4 أفضل من utf8 لأنه يدعم الإيموجي والرموز النادرة

        $username,
        // المعامل الثاني: اسم المستخدم (root)

        $password,
        // المعامل الثالث: كلمة المرور (فارغة)

        [
        // المعامل الرابع: مصفوفة الإعدادات [مفتاح => قيمة]
        // لضبط سلوك PDO

            PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
            // وضع الأخطاء: عند حدوث أي خطأ في SQL → إطلاق استثناء (Exception)
            // يجعل الأخطاء مرئية بدلاً من تجاهلها بصمت
            // يساعد في اكتشاف الأخطاء بسرعة أثناء التطوير

            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
            // وضع الجلب الافتراضي: عند جلب البيانات من قاعدة البيانات
            // FETCH_ASSOC = إرجاع النتائج كمصفوفة ترابطية (اسم العمود => القيمة)
            // مثال: $user['name'] بدلاً من $user[0]

            PDO::ATTR_EMULATE_PREPARES   => false,
            // تعطيل المحاكاة للاستعلامات المُحضَّرة (Prepared Statements)
            // true (الافتراضي): PDO يحاكي الاستعلامات على جانب PHP (أقل أماناً)
            // false: MySQL ينفّذها فعلياً على جانبه (أكثر أماناً وكفاءةً)
            // الفائدة: حماية أقوى ضد SQL Injection + أنواع بيانات أدق

        ]
        // إغلاق المصفوفة

    );
    // إغلاق استدعاء new PDO()

} catch (PDOException $e) {
// بداية كتلة catch: تُنفَّذ إذا فشل الاتصال
// PDOException = نوع الاستثناء الخاص بـ PDO
// $e = المتغير الذي يحتوي تفاصيل الخطأ

    die("❌ فشل الاتصال بقاعدة البيانات: " . $e->getMessage());
    // die(...) = إيقاف تنفيذ السكربت فوراً وطباعة النص
    // ❌ = إيموجي للتوضيح البصري
    // $e->getMessage() = جلب نص الخطأ (مثل: "Access denied for user...")
    // . = دمج (Concatenation) بين النص ورسالة الخطأ

}
// إغلاق كتلة catch