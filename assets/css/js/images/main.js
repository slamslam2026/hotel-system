// تأكيد الحذف لكل زر يحمل الكلاس confirm-delete
// ============================================

document.addEventListener('DOMContentLoaded', function () {
// ننتظر حتى يتم تحميل صفحة HTML بالكامل قبل تنفيذ الكود
// السبب: نضمن وجود جميع العناصر قبل التعامل معها

    document.querySelectorAll('.confirm-delete').forEach(function (btn) {
    // نجلب جميع العناصر التي تحمل الكلاس "confirm-delete"
    // ثم نمرّ عليها واحداً واحداً، و"btn" يمثل العنصر الحالي

        btn.addEventListener('click', function (e) {
        // نضيف مستمعاً لحدث النقر على الزر
        // "e" هو كائن الحدث الذي يحتوي معلومات عن النقرة

            if (!confirm('هل أنت متأكد من الحذف؟ لا يمكن التراجع.')) {
            // نافذة تأكيد:
            // - إذا ضغط "موافق" → ترجع true
            // - إذا ضغط "إلغاء" → ترجع false
            // ! يعني: إذا ضغط "إلغاء" (false)

                e.preventDefault();
                // نمنع السلوك الافتراضي للرابط (عدم الانتقال لصفحة الحذف)
                // بمعنى: إلغاء عملية الحذف

            }
            // إغلاق الشرط

        });
        // إغلاق دالة click

    });
    // إغلاق دالة forEach

});
// إغلاق دالة DOMContentLoaded

// ============================================
// إخفاء الرسائل التنبيهية تلقائياً بعد 5 ثوان
// ============================================

setTimeout(function () {
// ننتظر 5 ثوان قبل تنفيذ الكود التالي
// الفائدة: إعطاء المستخدم وقتاً كافياً لقراءة الرسالة

    document.querySelectorAll('.alert-dismissible').forEach(function (alert) {
    // نجلب جميع التنبيهات القابلة للإغلاق (بكلاس alert-dismissible)
    // ثم نمرّ عليها واحداً واحداً

        const bsAlert = bootstrap.Alert.getOrCreateInstance(alert);
        // نحصل على كائن Bootstrap للتحكم بالتنبيه
        // - إذا كان الكائن موجوداً → نجلبه
        // - إذا لم يكن موجوداً → ننشئ واحداً جديداً
        // "const" لأننا لن نعيد تعيين المتغير

        bsAlert.close();
        // نغلق التنبيه مع تأثير التلاشي الأنيق

    });
    // إغلاق دالة forEach

}, 5000);
// إغلاق دالة setTimeout
// 5000 ميلي ثانية = 5 ثوان

